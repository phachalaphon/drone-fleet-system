-- ตารางเก็บประวัติ Chat (โบนัส) รันใน Supabase SQL Editor 1 ครั้ง
CREATE TABLE IF NOT EXISTS chat_logs (
  log_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    uuid,
  question   text NOT NULL,
  answer     text,
  tools      jsonb,
  created_at timestamptz DEFAULT now()
);

ALTER TABLE chat_logs ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS chat_logs_insert ON chat_logs;
DROP POLICY IF EXISTS chat_logs_select ON chat_logs;
CREATE POLICY chat_logs_insert ON chat_logs FOR INSERT TO authenticated WITH CHECK (user_id = auth.uid());
CREATE POLICY chat_logs_select ON chat_logs FOR SELECT TO authenticated USING (user_id = auth.uid());
